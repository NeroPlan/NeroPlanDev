-- 초기 스키마 - ddl-auto: update 시절 Hibernate가 만들던 구조와 같음
-- 이미 테이블이 있는 기존 DB에서는 아무것도 하지 않도록 IF NOT EXISTS 사용 (application.yaml의 baseline 설정 참고)

CREATE TABLE IF NOT EXISTS users (
    user_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname      varchar(30)  NOT NULL,
    profile_image varchar(255),
    birth         date,
    gender        varchar(10),
    google_id     varchar(255),
    email         varchar(255),
    role          varchar(255) NOT NULL,
    CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT uk_users_google_id UNIQUE (google_id),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- 직접 올린 프로필 사진 - users 조회 때마다 이미지를 읽지 않도록 분리
CREATE TABLE IF NOT EXISTS user_profile_image (
    user_id      bigint PRIMARY KEY,
    data         bytea       NOT NULL,
    content_type varchar(30) NOT NULL
);
