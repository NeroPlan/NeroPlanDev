-- 초기 스키마 - ddl-auto: update 시절 Hibernate가 만들던 구조와 같음
-- 이미 테이블이 있는 기존 DB에서는 아무것도 하지 않도록 IF NOT EXISTS 사용 (application.yml의 baseline 설정 참고)

CREATE TABLE IF NOT EXISTS category (
    category_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time timestamp(6) without time zone,
    user_id      bigint      NOT NULL,
    name         varchar(50) NOT NULL,
    CONSTRAINT uk_category_user_id_name UNIQUE (user_id, name)
);

CREATE TABLE IF NOT EXISTS plan (
    plan_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content           varchar(255) NOT NULL,
    priority          bigint       NOT NULL,
    estimated_minutes integer,
    created_time      timestamp(6) without time zone,
    plan_date         date        DEFAULT CURRENT_DATE NOT NULL,
    postpone_count    integer     DEFAULT 0 NOT NULL,
    status            varchar(20) DEFAULT 'TODO' NOT NULL,
    completed_time    timestamp(6) without time zone,
    user_id           bigint,
    category_id       bigint,
    CONSTRAINT plan_status_check CHECK (status IN ('TODO', 'DONE')),
    CONSTRAINT fk_plan_category FOREIGN KEY (category_id) REFERENCES category (category_id)
);

CREATE TABLE IF NOT EXISTS plan_detail (
    plan_detail_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    success_rate      double precision,
    completion_rate   double precision,
    recommended_time  timestamp(6) without time zone,
    priority_reason   varchar(255),
    is_biased         boolean,
    biased_reason     varchar(255),
    recommended_order integer,
    analysis_status   varchar(20),
    record_count      integer,
    plan_id           bigint NOT NULL,
    CONSTRAINT plan_detail_analysis_status_check CHECK (analysis_status IN ('NO_RECORD', 'COLLECTING', 'PREDICTED')),
    CONSTRAINT fk_plan_detail_plan FOREIGN KEY (plan_id) REFERENCES plan (plan_id)
);
